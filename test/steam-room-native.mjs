import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import net from 'node:net';
import { spawn, spawnSync } from 'node:child_process';
import { once } from 'node:events';
import { fileURLToPath } from 'node:url';
import { connectPage, waitForPort, sleep } from './cdp.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = process.env.DEEPSCORD_ELECTRON_RUNTIME;
assert.ok(source, 'Set DEEPSCORD_ELECTRON_RUNTIME to a packaged Electron executable');
const tools = path.join(root, '.qa-tools');
fs.mkdirSync(tools, { recursive: true });
const temporary = fs.mkdtempSync(path.join(tools, 'steam-desktop-'));
const runtime = path.join(temporary, 'runtime');
const sourceApp = path.join(path.dirname(source), 'resources', 'app');
fs.cpSync(path.dirname(source), runtime, { recursive: true, filter: (entry) => entry !== sourceApp });
const runtimeApp = path.join(runtime, 'resources', 'app');
fs.cpSync(path.join(root, 'desktop'), runtimeApp, { recursive: true });
const runtimeServer = path.join(runtimeApp, 'app-server');
fs.mkdirSync(runtimeServer, { recursive: true });
fs.copyFileSync(path.join(root, 'server.js'), path.join(runtimeServer, 'server.js'));
for (const name of ['lib', 'public']) fs.cpSync(path.join(root, name), path.join(runtimeServer, name), { recursive: true });
const listener = net.createServer();
listener.listen(0, '127.0.0.1');
await once(listener, 'listening');
const address = listener.address();
assert.ok(address && typeof address !== 'string');
const port = address.port;
listener.close();
await once(listener, 'close');
const environment = { ...process.env, DEEPSCORD_USER_DATA: path.join(temporary, 'user-data') };
delete environment.ELECTRON_RUN_AS_NODE;
const logPath = path.join(temporary, 'native.log');
const log = fs.openSync(logPath, 'w');
const child = spawn(path.join(runtime, path.basename(source)), [`--remote-debugging-port=${port}`, '--remote-debugging-address=127.0.0.1'], { env: environment, windowsHide: true, stdio: ['ignore', log, log] });
const exited = once(child, 'exit');
let page = null;
let passed = false;
try {
  await waitForPort(port, 15000);
  page = await connectPage(port, 'file:');
  await page.waitFor('document.getElementById("version").textContent.includes("Electron")', { timeout: 10000, interval: 100, label: 'launcher ready' });
  await page.eval('document.getElementById("steamCreateBtn").click()', { awaitPromise: true, userGesture: true });
  await page.waitFor('!document.getElementById("steamCreated").hidden || (document.getElementById("error").classList.contains("show") && !document.getElementById("steamCreateBtn").disabled)', { timeout: 30000, interval: 100, label: 'Steam native room creation' });
  const created = await page.eval('({created: !document.getElementById("steamCreated").hidden, error: document.getElementById("error").textContent, validInvite: /^deepscord:\\/\\/steam\\?appid=480&lobby=/.test(document.getElementById("steamInvite").value)})', { awaitPromise: true, userGesture: true });
  assert.equal(created.created, true, created.error);
  assert.equal(created.validInvite, true);
  console.log('PASS real Steam lobby creation through the production desktop launcher');
  await page.eval('document.getElementById("steamEnterBtn").click()', { awaitPromise: true, userGesture: true });
  page.close();
  page = await connectPage(port, 'http://127.0.0.1:');
  await page.waitFor('!!document.getElementById("welcomeNameInput")', { timeout: 15000, interval: 100, label: 'fresh invitation welcome' });
  await page.eval('document.getElementById("welcomeNameInput").value = "Steam native test"; document.getElementById("welcomeEnterBtn").click()', { awaitPromise: true, userGesture: true });
  await page.waitFor('window.echo && window.echo.getState().roomReady === true', { timeout: 15000, interval: 100, label: 'authenticated Steam host room' });
  const state = await page.eval('window.echo.getState()', { awaitPromise: true, userGesture: true });
  assert.equal(state.mediaPolicy, 'direct');
  assert.equal(state.users.length, 1);
  const session = await page.eval('window.deepscord.getSteamSession()', { awaitPromise: true, userGesture: true });
  assert.equal(session.appId, 480);
  assert.equal(session.role, 'host');
  assert.equal(await page.eval('location.hash', { awaitPromise: true, userGesture: true }), '');
  assert.equal(await page.eval('localStorage.getItem("echo.password")', { awaitPromise: true, userGesture: true }), null);
  const denial = await page.eval('window.deepscord.createSteam({appId:480,stunUrls:[]}).then(() => "allowed", () => "denied")', { awaitPromise: true, userGesture: true });
  assert.equal(denial, 'denied');
  console.log('PASS authenticated room admission, automatic invitation password and restricted Steam IPC');
  await page.eval('window.echo.actions.joinVoice("ch-lobby")', { awaitPromise: true, userGesture: true });
  await page.waitFor('window.echo.getState().voiceChannelId === "ch-lobby" && window.echo.getVoiceStats().micReady', { timeout: 15000, interval: 100, label: 'real local microphone and room admission' });
  await page.eval('window.echo.actions.toggleMute(); window.echo.actions.leaveVoice()', { awaitPromise: true, userGesture: true });
  await page.waitFor('window.echo.getState().voiceChannelId === null', { timeout: 5000, interval: 100, label: 'voice leave' });
  console.log('PASS real microphone, voice admission, mute and leave through the Steam room bridge');
  await page.eval('window.echo.actions.selectChannel("ch-chat"); window.echo.actions.sendMessage("Steam signaling smoke")', { awaitPromise: true, userGesture: true });
  await page.waitFor('window.echo.getState().messageCounts["ch-chat"] >= 3', { timeout: 5000, interval: 100, label: 'room command round trip' });
  await page.eval('window.__steamReloadMarker = true', { awaitPromise: true, userGesture: true });
  await page.send('Page.reload');
  await page.waitFor('!window.__steamReloadMarker && window.echo && window.echo.getState().roomReady === true', { timeout: 10000, interval: 100, label: 'page reload admission' });
  assert.equal((await page.eval('window.echo.getState()', { awaitPromise: true, userGesture: true })).users.filter((user) => user.signalConnected).length, 1);
  console.log('PASS room text commands and reload without duplicate active membership');
  page.send('Runtime.evaluate', { expression: 'window.deepscord.quit()', userGesture: true }).catch((error) => console.warn('Native quit response unavailable', { message: error.message }));
  await Promise.race([exited, sleep(10000).then(() => { if (child.exitCode === null) throw new Error('Steam desktop did not quit'); })]);
  assert.equal(fs.readdirSync(path.join(temporary, 'user-data', 'steam-rooms')).length, 0);
  console.log('PASS Steam lobby and temporary room cleanup; cross-account join remains a field test');
  passed = true;
} finally {
  if (page) page.close();
  if (child.exitCode === null) spawnSync('taskkill', ['/PID', String(child.pid), '/T', '/F'], { windowsHide: true, stdio: 'ignore' });
  await exited;
  fs.closeSync(log);
  if (passed) {
    assert.equal(path.dirname(fs.realpathSync(temporary)), fs.realpathSync(tools));
    fs.rmSync(temporary, { recursive: true });
  } else console.error('Native Steam test diagnostics retained', { logPath });
}
