test('actual self-host server enforces claimed persistent owners, scoped roles, groups and moderation', { timeout:40000 }, async () => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(),'deepscord-roles-'));
  /** @type {Backend|null} */ let backend = null;
  try {
    backend = await launch(directory,{});
    const a = identity(), b = identity(), c = identity(), d = identity(), ordinary = identity();
    const owner = await connect(backend,'Owner');
    const claimFile = path.join(directory,'owner-claim.txt'), claimToken = fs.readFileSync(claimFile,'utf8').trim();
    assert.match(claimToken,/^[a-f0-9]{64}$/);
    await denied(owner,{ t:'createChannel', serverId:'srv-main', type:'text', name:'Unverified' });
    await denied(owner,{ t:'createServer', name:'Unverified domain' });
    await denied(owner,{ t:'claimOwner', token:claimToken });
    await authenticate(owner,a);
    const replayedOwnProof = await denied(owner,proof(owner,a));
    assert.match(string(replayedOwnProof.message),/过期|已使用/);
    await denied(owner,{ t:'createServer', name:'Before claim' });
    await denied(owner,{ t:'claimOwner', token:'0'.repeat(64) });
    const claimCursor = send(owner,{ t:'claimOwner', token:claimToken });
    const claimed = await receive(owner,claimCursor,message=>message.t === 'serverState' && object(message.policy).ownerKey === a.key,'owner token claim');
    assert.equal(claimed.ownerClaimAvailable,false);
    assert.equal(fs.existsSync(claimFile),false);
    let current = journal(claimed);
    await denied(owner,{ t:'claimOwner', token:claimToken });
    const expanded = await structure(owner,{ t:'createServer', name:'Owner-created domain' });
    const addedDomain = expanded.find(domain=>domain.name === 'Owner-created domain'); assert(addedDomain);
    assert.notEqual(addedDomain.id,object(claimed.server).id);
    const restoredDomains = await structure(owner,{ t:'deleteServer', serverId:addedDomain.id });
    assert(!restoredDomains.some(domain=>domain.id === addedDomain.id));
    const domainOwner = await connect(backend,'Domain owner'); await authenticate(domainOwner,b);
    const admin = await connect(backend,'Administrator'); await authenticate(admin,c);
    const special = await connect(backend,'Named group'); await authenticate(special,d);
    const member = await connect(backend,'Ordinary'); await authenticate(member,ordinary);
    await denied(member,{ t:'createChannel', serverId:'srv-main', type:'text', name:'Forbidden' });
    await denied(member,{ t:'createServer', name:'Forbidden domain' });
    current = await change(owner,a,current,{ type:'setDomainOwner', domainId:'srv-main', memberKey:b.key });
    current = await change(domainOwner,b,current,{ type:'setDomainAdmin', domainId:'srv-main', memberKey:c.key, enabled:true });
    await denied(domainOwner,{ t:'governanceChange', event:signedEvent(current,b,{ type:'setDomainOwner', domainId:'srv-main', memberKey:ordinary.key }) });
    await denied(admin,{ t:'governanceChange', event:signedEvent(current,c,{ type:'setDomainAdmin', domainId:'srv-main', memberKey:ordinary.key, enabled:true }) });
    await denied(admin,{ t:'governanceChange', event:signedEvent(current,c,{ type:'putGroup', domainId:'srv-main', groupId:'root', name:'Root', permissions:['manageChannels'] }) });
    let servers = await structure(admin,{ t:'createChannel', serverId:'srv-main', type:'text', name:'Admin-created' });
    const created = servers.find(server=>server.id === 'srv-main')?.channels.find(channel=>channel.name === 'Admin-created'); assert(created);
    servers = await structure(admin,{ t:'updateChannel', channelId:created.id, name:'Admin-updated' });
    assert.equal(servers.find(server=>server.id === 'srv-main')?.channels.find(channel=>channel.id === created.id)?.name,'Admin-updated');
    await denied(admin,{ t:'createChannel', serverId:'srv-night', type:'text', name:'Cross-domain' });
    await denied(admin,{ t:'updateChannel', channelId:'ch-night-text', name:'Cross-domain' });
    await denied(admin,{ t:'updateDomain', domainId:'srv-main', name:'Admin domain rename' });
    servers = await structure(admin,{ t:'deleteChannel', channelId:created.id });
    assert(!servers.flatMap(server=>server.channels).some(channel=>channel.id === created.id));
    current = await change(domainOwner,b,current,{ type:'putGroup', domainId:'srv-main', groupId:'builders', name:'Builders', permissions:['manageChannels'] });
    current = await change(domainOwner,b,current,{ type:'setMemberGroups', domainId:'srv-main', memberKey:d.key, groupIds:['builders'] });
    servers = await structure(special,{ t:'createChannel', serverId:'srv-main', type:'text', name:'Group-created' });
    const groupChannel = servers.find(server=>server.id === 'srv-main')?.channels.find(channel=>channel.name === 'Group-created'); assert(groupChannel);
    await denied(special,{ t:'createChannel', serverId:'srv-night', type:'text', name:'Group cross-domain' });
    current = await change(domainOwner,b,current,{ type:'setMemberGroups', domainId:'srv-main', memberKey:d.key, groupIds:[] });
    await denied(special,{ t:'updateChannel', channelId:groupChannel.id, name:'Revoked edit' });
    const messageId = await chat(member,'ch-chat','Ordinary members can still chat');
    await denied(member,{ t:'deleteMessage', channelId:'ch-chat', messageId });
    const deleteCursor = send(admin,{ t:'deleteMessage', channelId:'ch-chat', messageId });
    await receive(admin,deleteCursor,message=>message.t === 'messageDeleted' && message.messageId === messageId,'admin deletes domain message');
    const nightMessage = await chat(member,'ch-night-text','Other domain message');
    await denied(admin,{ t:'deleteMessage', channelId:'ch-night-text', messageId:nightMessage });
    await join(member,'ch-lobby');
    await denied(special,{ t:'disconnectVoice', userId:member.userId });
    const moderationCursor = send(admin,{ t:'disconnectVoice', userId:member.userId });
    await receive(admin,moderationCursor,message=>message.t === 'voiceState' && message.userId === member.userId && message.channelId === null,'admin removes ordinary voice peer');
    await join(domainOwner,'ch-lobby');
    await denied(admin,{ t:'disconnectVoice', userId:domainOwner.userId });
    await join(owner,'ch-lobby');
    await denied(domainOwner,{ t:'disconnectVoice', userId:owner.userId });
    await join(member,'ch-night-voice');
    await denied(admin,{ t:'disconnectVoice', userId:member.userId });
    const badSignature = signedEvent(current,a,{ type:'renameServer', name:'Forged name' });
    await denied(owner,{ t:'governanceChange', event:{ ...badSignature, signature:Buffer.alloc(64).toString('base64') } });
    const validRename = signedEvent(current,a,{ type:'renameServer', name:'Persistent server' });
    current = await change(owner,a,current,validRename.command);
    await denied(owner,{ t:'governanceChange', event:validRename });
    const impersonator = await connect(backend,'Impersonator');
    await denied(impersonator,{ ...proof(impersonator,ordinary), memberKey:a.key });
    const consumedFailedProof = await denied(impersonator,proof(impersonator,ordinary));
    assert.match(string(consumedFailedProof.message),/过期|已使用/);
    await denied(impersonator,{ t:'createServer', name:'Forged owner domain' });
    const replayTarget = await connect(backend,'Replay');
    await denied(replayTarget,proof(owner,a));
    await denied(replayTarget,{ t:'claimOwner', token:claimToken });
    const duplicate = await connect(backend,'Duplicate key');
    await denied(duplicate,proof(duplicate,a));
    await denied(duplicate,{ t:'createServer', name:'Duplicate owner' });
    const persistedDigest = current.digest;
    await stop(backend); backend = await launch(directory,{});
    const restoredOwner = await connect(backend,'Owner reconnect');
    const restoredOwnerState = await authenticate(restoredOwner,a);
    assert.equal(restoredOwnerState.selfKey,a.key);
    assert.equal(object(restoredOwnerState.policy).ownerKey,a.key);
    assert.equal(object(restoredOwnerState.server).name,'Persistent server');
    assert.equal(journal(restoredOwnerState).digest,persistedDigest);
    const restoredDomainOwner = await connect(backend,'Domain owner reconnect');
    const restoredDomainState = await authenticate(restoredDomainOwner,b);
    assert(Array.isArray(restoredDomainState.capabilities));
    assert.equal(object(restoredDomainState.capabilities.find(value=>object(value).domainId === 'srv-main')).role,'domain-owner');
    const restoredAdmin = await connect(backend,'Admin reconnect');
    const restoredAdminState = await authenticate(restoredAdmin,c);
    assert(Array.isArray(restoredAdminState.capabilities));
    assert.equal(object(restoredAdminState.capabilities.find(value=>object(value).domainId === 'srv-main')).role,'domain-admin');
    await structure(restoredAdmin,{ t:'updateChannel', channelId:groupChannel.id, name:'After real restart' });
    await denied(restoredAdmin,{ t:'updateChannel', channelId:'ch-night-text', name:'Still cross-domain' });
    const restoredSpecial = await connect(backend,'Revoked group reconnect'); await authenticate(restoredSpecial,d);
    await denied(restoredSpecial,{ t:'createChannel', serverId:'srv-main', type:'text', name:'Revoked after restart' });
    assert.equal(fs.existsSync(claimFile),false);
  } catch (error) {
    if (backend) console.error(JSON.stringify({ event:'server_roles_failure', output:backend.output() }));
    throw error;
  } finally { if (backend) await stop(backend); cleanup(directory); }
});

test('ordinary signed replica votes cannot smuggle unauthorized channel changes into client-owned rooms', { timeout:15000 }, async () => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(),'deepscord-roles-'));
  /** @type {Backend|null} */ let backend = null;
  try {
    const creator = identity(), ordinary = identity();
    const anchor = { version:/** @type {const} */ (1), roomId:randomUUID(), creatorKey:creator.key };
    const document = replica.createRoomDocument(anchor,0,[{ id:'srv-main', name:'Legacy domain', icon:'D', color:'#123456', channels:[{ id:'ch-chat', name:'Chat', type:'text', userLimit:0 }] }]);
    const seedPath = path.join(directory,'seed.json'); fs.writeFileSync(seedPath,JSON.stringify(document));
    backend = await launch(path.join(directory,'backend'),{ ECHO_ROOM_ID:anchor.roomId, ECHO_ROOM_CREATOR_KEY:anchor.creatorKey, ECHO_ROOM_SEED_PATH:seedPath });
    const client = await connect(backend,'Ordinary replica'); await authenticate(client,ordinary);
    const offer = await receive(client,0,message=>message.t === 'roomSyncOffer','actual client-owned sync offer');
    const offered = replica.parseRoomDocument(object(offer.document),anchor);
    const forged = replica.createRoomDocument(anchor,offered.revision + 1,offered.servers.map(server=>({ ...server, channels:[...server.channels,{ id:'ch-forged', name:'Unauthorized', type:'text', userLimit:0 }] })));
    const roundId = string(offer.roundId);
    const signature = sign(null,Buffer.from(replica.roomVotePayload(roundId,ordinary.key,forged,false)),ordinary.privateKey).toString('base64');
    const cursor = send(client,{ t:'roomSyncVote', roundId, memberKey:ordinary.key, document:forged, signature, fresh:false });
    const rejected = await receive(client,cursor,message=>message.t === 'error' && message.code === 'room-sync-rejected','valid signed but unauthorized replica vote');
    assert.match(string(rejected.message),/srv-main.*manageChannels/);
    const persisted = object(JSON.parse(fs.readFileSync(path.join(directory,'backend','room-identity.json'),'utf8')));
    assert.equal(replica.parseRoomDocument(object(persisted.document),anchor).digest,offered.digest);
  } catch (error) {
    if (backend) console.error(JSON.stringify({ event:'server_roles_vote_failure', output:backend.output() }));
    throw error;
  } finally { if (backend) await stop(backend); cleanup(directory); }
});

test('suspended voice owners remain protected and resumed connections must prove their management identity again', { timeout:20000 }, async () => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(),'deepscord-roles-'));
  /** @type {Backend|null} */ let backend = null;
  try {
    backend = await launch(directory,{});
    const a = identity(), b = identity(), c = identity(), attacker = identity();
    const owner = await connectHello(backend,{ t:'hello', name:'Resumable owner', color:'#123456', password:'', resumable:true });
    await authenticate(owner,a);
    const claimToken = fs.readFileSync(path.join(directory,'owner-claim.txt'),'utf8').trim();
    const claimCursor = send(owner,{ t:'claimOwner', token:claimToken });
    let current = journal(await receive(owner,claimCursor,message=>message.t === 'serverState' && object(message.policy).ownerKey === a.key,'resumable owner claim'));
    const domainOwner = await connectHello(backend,{ t:'hello', name:'Resumable domain owner', color:'#123456', password:'', resumable:true });
    await authenticate(domainOwner,b);
    const admin = await connect(backend,'Active admin'); await authenticate(admin,c);
    current = await change(owner,a,current,{ type:'setDomainOwner', domainId:'srv-main', memberKey:b.key });
    current = await change(domainOwner,b,current,{ type:'setDomainAdmin', domainId:'srv-main', memberKey:c.key, enabled:true });
    await join(owner,'ch-lobby'); await join(domainOwner,'ch-lobby');
    const ownerWelcome = owner.messages.find(message=>message.t === 'welcome'); assert(ownerWelcome);
    const domainWelcome = domainOwner.messages.find(message=>message.t === 'welcome'); assert(domainWelcome);
    const disconnectCursor = admin.messages.length;
    owner.socket.close(); domainOwner.socket.close();
    await Promise.all([owner.closed,domainOwner.closed]);
    await receive(admin,disconnectCursor,message=>message.t === 'userConnection' && message.id === owner.userId && message.connected === false,'owner signaling outage');
    await receive(admin,disconnectCursor,message=>message.t === 'userConnection' && message.id === domainOwner.userId && message.connected === false,'domain owner signaling outage');
    const ownerProtected = await denied(admin,{ t:'disconnectVoice', userId:owner.userId });
    assert.match(string(ownerProtected.message),/同级|更高/);
    const domainProtected = await denied(admin,{ t:'disconnectVoice', userId:domainOwner.userId });
    assert.match(string(domainProtected.message),/同级|更高/);
    const peersCursor = send(admin,{ t:'joinVoice', channelId:'ch-lobby', muted:false, deafened:false });
    const peers = await receive(admin,peersCursor,message=>message.t === 'voicePeers' && message.channelId === 'ch-lobby','suspended owners remain in voice');
    assert(Array.isArray(peers.peers));
    for (const [userId,key] of [[owner.userId,a.key],[domainOwner.userId,b.key]]) {
      const peer = object(peers.peers.find(value=>object(value).id === userId));
      assert.equal(peer.signalConnected,false);
      assert.equal(peer.memberKey,key);
    }
    const publicKeyImpersonator = await connectHello(backend,{ t:'hello', name:'Public key impostor', color:'#123456', password:'', resumable:false, memberKey:a.key });
    const unverifiedState = await receive(publicKeyImpersonator,0,message=>message.t === 'serverState','public key is not a proof');
    assert.equal(unverifiedState.selfKey,null);
    await denied(publicKeyImpersonator,{ t:'createServer', name:'Public-key privilege escalation' });
    await denied(publicKeyImpersonator,{ t:'createChannel', serverId:'srv-main', type:'text', name:'Public-key channel' });
    await denied(publicKeyImpersonator,{ ...proof(publicKeyImpersonator,attacker), memberKey:a.key });
    const resumed = await connectHello(backend,{ t:'hello', name:'Resumed owner session', color:'#123456', password:'', resumable:true, resumeToken:string(ownerWelcome.resumeToken), memberKey:a.key });
    assert.equal(resumed.userId,owner.userId);
    const resumedState = await receive(resumed,0,message=>message.t === 'serverState','resumed unproven management identity');
    assert.equal(resumedState.selfKey,null);
    assert(Array.isArray(resumedState.members));
    assert.equal(object(resumedState.members.find(value=>object(value).userId === owner.userId)).memberKey,a.key);
    await denied(resumed,{ t:'createServer', name:'Session-only privilege escalation' });
    await denied(resumed,{ t:'createChannel', serverId:'srv-main', type:'text', name:'Resume without proof' });
    await denied(resumed,{ t:'disconnectVoice', userId:domainOwner.userId });
    const restoredState = await authenticate(resumed,a);
    assert.equal(restoredState.selfKey,a.key);
    const added = await structure(resumed,{ t:'createChannel', serverId:'srv-main', type:'text', name:'Proven channel' });
    assert(added.find(domain=>domain.id === 'srv-main')?.channels.some(channel=>channel.name === 'Proven channel'));
    await denied(admin,{ t:'disconnectVoice', userId:resumed.userId });
    const resumedDomain = await connectHello(backend,{ t:'hello', name:'Resumed domain owner', color:'#123456', password:'', resumable:true, resumeToken:string(domainWelcome.resumeToken), memberKey:b.key });
    assert.equal(resumedDomain.userId,domainOwner.userId);
    await denied(resumedDomain,{ t:'updateDomain', domainId:'srv-main', name:'Session-only domain edit' });
    await denied(admin,{ t:'disconnectVoice', userId:resumedDomain.userId });
    await authenticate(resumedDomain,b);
    const renamed = await structure(resumedDomain,{ t:'updateDomain', domainId:'srv-main', name:'Proven domain' });
    assert.equal(renamed.find(domain=>domain.id === 'srv-main')?.name,'Proven domain');
  } catch (error) {
    if (backend) console.error(JSON.stringify({ event:'server_roles_suspension_failure', output:backend.output() }));
    throw error;
  } finally { if (backend) await stop(backend); cleanup(directory); }
});
